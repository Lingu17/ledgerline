@needs_pg
def test_postgres_end_to_end_sample_walkthrough_and_restart_continuity():
    from .accuracy_harness import run_sample_walkthrough

    app = _pg_app()
    prefix = app.state.settings.pg_schema_prefix
    result = run_sample_walkthrough(app, 0)
    assert result["score"]["ledger_balanced"] and result["score"]["double_payments"] == 0 and result["score"]["deposits"] == 6
    assert result["deposits"]["DEP-1005"][:2] == ("verified_advance_credit", "credited")
    assert result["deposits"]["DEP-1006"][1] == "refunded"
    owner = _signup(app, "owner@pg.test")
    org = owner.org_id
    keys_before = owner.post("/api/deposits/DEP-1006/ask-agent").json()["verification"]["verdict"]
    assert keys_before == "verified"
    # "Restart": a brand-new app process on the same schemas sees the same data and the same signing identities.
    pg.close_all()
    app2 = _pg_app(prefix=prefix)
    again = TestClient(app2)
    r = again.post("/api/auth/login", json={"email": "owner@pg.test", "password": __import__("tests.conftest", fromlist=["PASSWORD"]).PASSWORD})
    assert r.status_code == 200 and r.json()["organization"]["id"] == org
    again.headers["X-CSRF-Token"] = r.json()["csrf_token"]
    assert len(again.get("/api/deposits").json()) == 6
    v = again.post("/api/deposits/DEP-1004/ask-agent").json()["verification"]
    assert v["verdict"] == "rejected" and "belongs to another customer" in v["reason"]  # signature verified, record check failed


@needs_pg
def test_postgres_tenant_schemas_and_privileges():
    app = _pg_app()
    a, b = _signup(app, "a@pg.test"), _signup(app, "b@pg.test", start="empty")
    assert b.get("/api/deposits/DEP-1006").status_code == 404
    # Positive: a member of two organizations can switch between them.
    second = a.post("/api/organizations", json={"name": "A second org", "start_with": "empty"}).json()["organization"]["id"]
    assert second != a.org_id
    r = a.post("/api/auth/switch-organization", json={"organization_id": a.org_id})
    assert r.status_code == 200 and r.json()["organization"]["id"] == a.org_id
    # Negative: B cannot switch into A's organization, and B's active organization is unchanged.
    r = b.post("/api/auth/switch-organization", json={"organization_id": a.org_id})
    assert r.status_code == 403
    assert b.get("/api/auth/me").json()["organization"]["id"] == b.org_id
    s = app.state.settings
    conn = pg.PgConnection(PG_URL, pg.schema_for(s.pg_schema_prefix, "t", b.org_id))
    try:
        # A tenant connection resolves unqualified names in its own schema only.
        assert conn.execute("SELECT COUNT(*) FROM deposits").fetchone()[0] == 0
        rls = conn.execute("SELECT bool_and(relrowsecurity) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                           "WHERE n.nspname = current_schema() AND c.relkind = 'r'").fetchone()[0]
        assert rls is True
        public = conn.execute("SELECT has_schema_privilege('public', current_schema(), 'USAGE')").fetchone()[0]
        assert public is False
        enc = conn.execute("SELECT private_key_enc FROM agent_keys").fetchall()
        assert enc == []  # empty workspace has no agents
    finally:
        conn.close()
    conn = pg.PgConnection(PG_URL, pg.schema_for(s.pg_schema_prefix, "t", a.org_id))
    try:
        rows = conn.execute("SELECT customer_id, private_key_enc FROM agent_keys").fetchall()
        assert len(rows) == 6 and all(r["private_key_enc"].startswith("v1:") for r in rows)
    finally:
        conn.close()


