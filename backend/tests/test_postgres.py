# --------------------------------------------------------------------------- translation (no database)
def test_translation_of_sqlite_dialect():
    t = pg.translate
    assert t("SELECT * FROM x WHERE a = ? AND b LIKE ?") == "SELECT * FROM x WHERE a = %s AND b ILIKE %s"
    assert t("INSERT OR IGNORE INTO m VALUES (?,?)") == "INSERT INTO m VALUES (%s,%s) ON CONFLICT DO NOTHING"
    assert t("SELECT 1 FROM e WHERE memo LIKE 'FX %' AND q = '?'") == "SELECT 1 FROM e WHERE memo ILIKE 'FX %%' AND q = '?'"
    assert t("SELECT json_extract(detail,'$.buy_currency') FROM o") == "SELECT (detail::jsonb ->> 'buy_currency') FROM o"
    ddl = t("CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, amount_minor INTEGER NOT NULL, email TEXT UNIQUE COLLATE NOCASE)")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl and "amount_minor BIGINT" in ddl and "NOCASE" not in ddl
    assert "information_schema.columns" in t("PRAGMA table_info(approvals)")


def test_schema_names_are_validated():
    assert pg.schema_for("ll", "t", "org_0123456789ab") == "ll_t_org_0123456789ab"
    for bad in ("ll", "LL"), ("ll", "t; drop"), ("ll-x", "t"):
        with pytest.raises(ValueError):
            pg.schema_for(bad[0], bad[1], "org_0123456789ab")


def test_key_encryption_is_bound_to_organization_and_customer():
    from ledgerline.db import PgTarget
    from ledgerline.payer_agents.keys import KeyStoreError, decrypt, encrypt

    a, b = PgTarget("postgresql://x", "ll_t_org_aaaaaaaaaaaa"), PgTarget("postgresql://x", "ll_t_org_bbbbbbbbbbbb")
    secret = "s" * 40
    blob = encrypt(secret, a, "CUST-ACME", "private-key-material")
    assert "private-key-material" not in blob and decrypt(secret, a, "CUST-ACME", blob) == "private-key-material"
    for args in ((secret, b, "CUST-ACME"), (secret, a, "CUST-FJORD"), ("t" * 40, a, "CUST-ACME")):
        with pytest.raises(KeyStoreError):
            decrypt(*args, blob)


# --------------------------------------------------------------------------- live PostgreSQL
def _pg_app(prefix=None, **extra):
    from ledgerline.api.app import create_app
    from ledgerline.config import load_settings

    return create_app(load_settings({
        "LEDGERLINE_DATABASE_URL": PG_URL, "LEDGERLINE_PG_SCHEMA_PREFIX": prefix or "auto",
        "LEDGERLINE_SECRET_KEY": "test-secret-" + "k" * 32, "LEDGERLINE_PAYER_MCP_TRANSPORT": "memory",
        "LEDGERLINE_DATA_DIR": os.environ.get("TMP", "/tmp") + "/ll-pg-" + secrets.token_hex(3),
        "GOOGLE_CLIENT_ID": "", "APPLE_CLIENT_ID": "", "ANTHROPIC_API_KEY": "", **extra}))


def _signup(app, email, start="sample"):
    from .conftest import signup

    c = TestClient(app)
    signup(c, email=email, org=email.split("@")[0], start_with=start)
    return c


@needs_pg
def test_postgres_end_to_end_sample_walkthrough_and_restart_continuity():
    from .accuracy_harness import run_sample_walkthrough

    app = _pg_app()
    prefix = app.state.settings.pg_schema_prefix
    result = run_sample_walkthrough(app, 0)
    assert result["score"]["ledger_balanced"] and result["score"]["double_payments"] == 0 and result["score"]["deposits"] == 6
    assert result["deposits"]["DEP-1005"][:2] == ("verified_advance_credit", "credited")
    assert result["deposits"]["DEP-1006"][1] == "refunded"
    owner = _signup(app, "owner@pg.test")
    org = owner.org_id
    keys_before = owner.post("/api/deposits/DEP-1006/ask-agent").json()["verification"]["verdict"]
    assert keys_before == "verified"
    # "Restart": a brand-new app process on the same schemas sees the same data and the same signing identities.
    pg.close_all()
    app2 = _pg_app(prefix=prefix)
    again = TestClient(app2)
    r = again.post("/api/auth/login", json={"email": "owner@pg.test", "password": __import__("tests.conftest", fromlist=["PASSWORD"]).PASSWORD})
    assert r.status_code == 200 and r.json()["organization"]["id"] == org
    again.headers["X-CSRF-Token"] = r.json()["csrf_token"]
    assert len(again.get("/api/deposits").json()) == 6
    v = again.post("/api/deposits/DEP-1004/ask-agent").json()["verification"]
    assert v["verdict"] == "rejected" and "belongs to another customer" in v["reason"]  # signature verified, record check failed


@needs_pg
def test_postgres_tenant_schemas_and_privileges():
    app = _pg_app()
    a, b = _signup(app, "a@pg.test"), _signup(app, "b@pg.test", start="empty")
    assert b.get("/api/deposits/DEP-1006").status_code == 404
    assert b.post("/auth/switch-organization", json={"organization_id": a.org_id}).status_code in (403, 404)
    s = app.state.settings
    conn = pg.PgConnection(PG_URL, pg.schema_for(s.pg_schema_prefix, "t", b.org_id))
    try:
        # A tenant connection resolves unqualified names in its own schema only.
        assert conn.execute("SELECT COUNT(*) FROM deposits").fetchone()[0] == 0
        rls = conn.execute("SELECT bool_and(relrowsecurity) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                           "WHERE n.nspname = current_schema() AND c.relkind = 'r'").fetchone()[0]
        assert rls is True
        public = conn.execute("SELECT has_schema_privilege('public', current_schema(), 'USAGE')").fetchone()[0]
        assert public is False
        enc = conn.execute("SELECT private_key_enc FROM agent_keys").fetchall()
        assert enc == []  # empty workspace has no agents
    finally:
        conn.close()
    conn = pg.PgConnection(PG_URL, pg.schema_for(s.pg_schema_prefix, "t", a.org_id))
    try:
        rows = conn.execute("SELECT customer_id, private_key_enc FROM agent_keys").fetchall()
        assert len(rows) == 6 and all(r["private_key_enc"].startswith("v1:") for r in rows)
    finally:
        conn.close()


@needs_pg
def test_postgres_concurrent_refund_execution_moves_money_once():
    app = _pg_app()
    c = _signup(app, "race@pg.test")
    for step in ["links", "agents", "treasury"]:
        assert c.post("/api/demo/step", json={"step": step}).status_code == 200
    a = next(x for x in c.get("/api/approvals").json() if x["status"] == "pending")
    approver = TestClient(app)
    from .conftest import PASSWORD

    inv = c.post("/api/team/invitations", json={"email": "op@pg.test", "role": "operator"}).json()["invite_path"].split("token=")[1]
    m = approver.post(f"/api/invitations/{inv}/accept", json={"name": "op", "password": PASSWORD}).json()
    approver.headers["X-CSRF-Token"] = m["csrf_token"]
    assert approver.post(f"/api/approvals/{a['id']}/approve", json={"scope_hash": a["scope_hash"]}).status_code == 200
    results = []

    def run():
        results.append(c.post(f"/api/approvals/{a['id']}/execute").status_code)

    threads = [threading.Thread(target=run) for _ in range(6)]
    [t.start() for t in threads]
    [t.join() for t in threads]
    assert results.count(200) >= 1
    ops = c.get("/api/deposits/DEP-1006").json()["operations"]
    assert len([o for o in ops if o["kind"] == "refund" and o["status"] not in ("failed", "cancelled")]) == 1
    assert c.get("/api/ledger").json()["conservation"]["all_balanced"]


