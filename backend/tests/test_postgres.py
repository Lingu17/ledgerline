# --------------------------------------------------------------------------- translation (no database)
def test_translation_of_sqlite_dialect():
    t = pg.translate
    assert t("SELECT * FROM x WHERE a = ? AND b LIKE ?") == "SELECT * FROM x WHERE a = %s AND b ILIKE %s"
    assert t("INSERT OR IGNORE INTO m VALUES (?,?)") == "INSERT INTO m VALUES (%s,%s) ON CONFLICT DO NOTHING"
    assert t("SELECT 1 FROM e WHERE memo LIKE 'FX %' AND q = '?'") == "SELECT 1 FROM e WHERE memo ILIKE 'FX %%' AND q = '?'"
    assert t("SELECT json_extract(detail,'$.buy_currency') FROM o") == "SELECT (detail::jsonb ->> 'buy_currency') FROM o"
    ddl = t("CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, amount_minor INTEGER NOT NULL, email TEXT UNIQUE COLLATE NOCASE)")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl and "amount_minor BIGINT" in ddl and "NOCASE" not in ddl
    assert "information_schema.columns" in t("PRAGMA table_info(approvals)")


