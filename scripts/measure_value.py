"""What the rules decide on their own, measured on the accuracy harness's synthetic companies, and written to a report.

  backend\\.venv\\Scripts\\python scripts\\measure_value.py --seeds 200 --minutes 5

Each seed is the same fresh synthetic company the accuracy run builds (made-up customers, invoices and payments driven
through the real API in-process: no network, no Airwallex, no Claude). For every payment it reads the first plan the
rules made, before any person touched it, and counts what that plan needed. Hours saved is an assumption times a count,
not a measurement of anyone's time.
"""
from __future__ import annotations

import argparse
import sys
import tempfile
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from ledgerline.api.app import create_app  # noqa: E402
from ledgerline.config import load_settings  # noqa: E402
from tests.accuracy_harness import Scenario  # noqa: E402

CLOSED = {"clean_match", "clean_with_fee"}


def first_plan_outcome(plan: dict) -> str:
    types = {a["type"] for a in plan["actions"]}
    if "escalate" in types:
        return "escalated"
    if "ask_payer_agent" in types:
        return "ask_agent"
    return "closed" if plan["category"] in CLOSED else "decided_open"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=200)
    ap.add_argument("--first", type=int, default=1)
    ap.add_argument("--minutes", type=float, default=5.0, help="assumed minutes a person spends matching one payment by hand")
    ap.add_argument("--report", default=str(ROOT / "docs" / "MEASURED_VALUE.md"))
    args = ap.parse_args()

    started = time.time()
    outcome: Counter[str] = Counter()
    category: Counter[tuple[str, str]] = Counter()
    refunds_sent = refund_approvals = companies = 0
    mix: Counter[str] = Counter()
    with tempfile.TemporaryDirectory(prefix="ledgerline-value-") as tmp:
        settings = load_settings({"LEDGERLINE_DATA_DIR": tmp, "LEDGERLINE_SIGNUP_PER_IP_HOUR": "100000", "LEDGERLINE_SIGNUP_PER_IP_DAY": "100000",
                                  "LEDGERLINE_SIGNUP_PER_DAY": "100000", "LEDGERLINE_PAYER_MCP_TRANSPORT": "memory",
                                  "LEDGERLINE_SAMPLE_WORKSPACE": "1", "ANTHROPIC_API_KEY": "", "AIRWALLEX_CLIENT_ID": "",
                                  "AIRWALLEX_API_KEY": "", "GOOGLE_CLIENT_ID": "", "APPLE_CLIENT_ID": "", "LEDGERLINE_LOG_LEVEL": "WARNING"})
        app = create_app(settings)
        for seed in range(args.first, args.first + args.seeds):
            s = Scenario(app, seed)
            s.run()  # also checks every payment against the independent reference model; raises on a mismatch
            companies += 1
            mix.update({k: v for k, v in s.stats.items() if k.startswith("pay_")})
            for dep_id in s.m.deposits:
                plan = s.c.get(f"/api/deposits/{dep_id}").json()["plans"][0]
                o = first_plan_outcome(plan)
                outcome[o] += 1
                category[(o, plan["category"])] += 1
            refunds_sent += sum(1 for op in s.c.get("/api/operations").json() if op["kind"] == "refund")
            refund_approvals += sum(1 for a in s.c.get("/api/approvals").json() if a["operation_type"] == "refund")
            print(f"seed {seed}: ok", flush=True)

    total = sum(outcome.values())
    no_person = outcome["closed"] + outcome["decided_open"]
    pct = lambda n: f"{100 * n / total:.1f}%"  # noqa: E731
    hours = no_person * args.minutes / 60
    by_cat = lambda o: ", ".join(f"{c.replace('_', ' ')} {n:,}" for (oo, c), n in sorted(category.items(), key=lambda kv: -kv[1]) if oo == o)  # noqa: E731
    lines = [
        "# Measured value on synthetic companies",
        "",
        "**Synthetic data only.** These are made-up companies, not customers. They show what the rules decide on their own "
        "for this mix of payments; a real company's mix will differ, and only a pilot can measure real time saved.",
        "",
        f"{companies} synthetic companies (seeds {args.first}–{args.first + args.seeds - 1}, the same ones the "
        f"[accuracy run](ACCURACY_REPORT.md) checks), {total:,} payments, in {time.time() - started:.0f} s. "
        "Generated by `scripts/measure_value.py`. For each payment it reads the **first plan the rules made**, before any "
        "person acted. Automatic asking of payer agents is switched off here, as in the accuracy run, so no payer agent answered.",
        "",
        f"The generator makes hard cases on purpose, so these shares are lower than a tidy company's would be: of the payments it "
        f"generated, {mix['pay_noref']:,} had no reference at all ({mix['pay_noref_same_amount']:,} of them for exactly an open "
        f"invoice's balance, which must never be matched on amount alone), {mix['pay_duplicate']:,} looked like "
        f"duplicates, {mix['pay_over']:,} were overpayments and {mix['pay_stranger']:,} came from unknown payers.",
        "",
        "| First plan | Payments | Share | What it was |",
        "|:--|--:|--:|:--|",
        f"| Closed with no person | {outcome['closed']:,} | {pct(outcome['closed'])} | {by_cat('closed')} |",
        f"| Decided with no person, still open | {outcome['decided_open']:,} | {pct(outcome['decided_open'])} | {by_cat('decided_open')}: applied, the rest is a balance request |",
        f"| Waiting for the payer's agent | {outcome['ask_agent']:,} | {pct(outcome['ask_agent'])} | {by_cat('ask_agent')}: customers with a registered agent; a person decides if it cannot answer |",
        f"| Escalated to a person, with its reason | {outcome['escalated']:,} | {pct(outcome['escalated'])} | {by_cat('escalated')} |",
        "",
        f"- **Decided with no person: {no_person:,} of {total:,} ({pct(no_person)}).**",
        f"- **Refunds sent without verified evidence or a person: {refunds_sent}.** Every apparent duplicate and overpayment was "
        "held (asked about, or escalated) instead of refunded. "
        f"Refund approvals created: {refund_approvals}.",
        f"- **Hours of matching saved, if each payment takes {args.minutes:g} minutes by hand: {hours:,.0f} hours** across the "
        f"{companies} companies, about {hours / companies:.1f} hours each. The {args.minutes:g} minutes is an assumption, not a "
        "measurement; the hours scale with it.",
        "",
        "## Wrong refunds avoided",
        "",
        "No payer agent answers in this synthetic run, so it cannot show a refund being dropped. The reference company shows it: "
        "DEP-1005 looks like a second payment of a paid invoice, so the rules propose a refund; the payer's agent answers with a "
        "signed claim that it is an advance, all three checks pass, and the refund is dropped before any money moves "
        "(identical in all 25 walkthroughs of the [accuracy run](ACCURACY_REPORT.md)). That is one case, not a rate.",
        "",
        "## What this does not measure",
        "",
        "- How often real payer agents exist and answer, and how often their answers pass the three checks.",
        "- A real company's payment mix, which decides the shares above.",
        "- Time actually spent per payment, which the minutes assumption stands in for.",
        "",
    ]
    Path(args.report).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{total} payments; no person {no_person} ({pct(no_person)}); escalated {outcome['escalated']}; ask agent {outcome['ask_agent']}; "
          f"refunds sent {refunds_sent}; hours {hours:.0f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
