"""Run the randomized end-to-end accuracy harness for many seeds and write a report.

  backend\\.venv\\Scripts\\python scripts\\accuracy_run.py --seeds 200 --walkthroughs 25

Each seed is a fresh synthetic company driven through the real API in-process
(no network, no Airwallex, no Claude). Throwaway data lives in a temp directory.
Exit code 1 if any seed disagrees with the reference model.
"""
from __future__ import annotations

import argparse
import sys
import tempfile
import time
import traceback
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from ledgerline.api.app import create_app  # noqa: E402
from ledgerline.config import load_settings  # noqa: E402
from tests.accuracy_harness import Mismatch, Scenario, run_sample_walkthrough  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=200)
    ap.add_argument("--first", type=int, default=1)
    ap.add_argument("--walkthroughs", type=int, default=25)
    ap.add_argument("--report", default=str(ROOT / "docs" / "ACCURACY_REPORT.md"))
    args = ap.parse_args()

    started = time.time()
    with tempfile.TemporaryDirectory(prefix="ledgerline-accuracy-") as tmp:
        settings = load_settings({"LEDGERLINE_DATA_DIR": tmp, "LEDGERLINE_SIGNUP_PER_IP_HOUR": "100000", "LEDGERLINE_SIGNUP_PER_IP_DAY": "100000", "LEDGERLINE_SIGNUP_PER_DAY": "100000", "LEDGERLINE_PAYER_MCP_TRANSPORT": "memory",
                                  "LEDGERLINE_SAMPLE_WORKSPACE": "1", "ANTHROPIC_API_KEY": "", "AIRWALLEX_CLIENT_ID": "",
                                  "AIRWALLEX_API_KEY": "", "GOOGLE_CLIENT_ID": "", "APPLE_CLIENT_ID": "", "LEDGERLINE_LOG_LEVEL": "WARNING"})
        app = create_app(settings)
        stats: Counter[str] = Counter()
        failures: list[tuple[int, str]] = []
        checks = 0
        prev = None
        for seed in range(args.first, args.first + args.seeds):
            s = None
            try:
                s = Scenario(app, seed)
                s.run()
                if prev is not None:
                    s.isolation_check(prev)
                    prev.isolation_check(s)
                prev = s
            except Mismatch as exc:
                failures.append((seed, str(exc)))
            except Exception:  # noqa: BLE001 - a crash is a failure too
                failures.append((seed, traceback.format_exc()))
            if s is not None:
                stats.update(s.stats)
                stats["deposits"] += len(s.m.deposits)
                checks += s.checks
            print(f"seed {seed}: {'FAIL' if failures and failures[-1][0] == seed else 'ok'}", flush=True)

        walk_results = []
        for n in range(args.walkthroughs):
            try:
                walk_results.append(run_sample_walkthrough(app, n))
            except AssertionError as exc:
                failures.append((-1 - n, f"walkthrough {n}: {exc}"))
        walk_consistent = len({repr(sorted(w["deposits"].items())) for w in walk_results}) <= 1
        walk_ok = walk_consistent and all(w["score"]["ledger_balanced"] and w["score"]["double_payments"] == 0
                                          and w["score"]["deposits"] == 6 for w in walk_results)
        if walk_results and not walk_ok:
            failures.append((0, f"walkthrough results differ or failed: {[w['score'] for w in walk_results][:3]}"))

    elapsed = time.time() - started
    lines = [
        "# Accuracy run",
        "",
        f"Seeds {args.first}–{args.first + args.seeds - 1} ({args.seeds} synthetic companies) and {args.walkthroughs} sample-company walkthroughs, "
        f"in {elapsed:.0f} s. Generated by `scripts/accuracy_run.py`; harness `backend/tests/accuracy_harness.py`.",
        "",
        f"**Result: {'PASS' if not failures else f'{len(failures)} FAILURE(S)'}** · {checks:,} individual checks · {stats['deposits']:,} payments · "
        f"{stats['invoices']:,} invoices",
        "",
        "## What each seed did (totals across all seeds)",
        "",
        "| Activity | Count |",
        "|---|---|",
    ]
    for k, v in sorted(stats.items()):
        if k != "deposits":
            lines.append(f"| {k} | {v:,} |")
    lines += ["", "## Sample-company walkthrough", ""]
    if walk_results:
        w = walk_results[0]
        lines.append(f"{len(walk_results)} runs, identical per-deposit outcomes: **{walk_consistent}**. Scorecard: `{w['score']}`")
        lines.append("")
        lines += ["| Deposit | Category | Status | Allocated | Unapplied |", "|---|---|---|---|---|"]
        for did, (cat, st, alloc, un) in sorted(w["deposits"].items()):
            lines.append(f"| {did} | {cat} | {st} | {alloc} | {un} |")
    lines += ["", "## Failures", ""]
    lines += [f"- seed {s}: ```{msg[:1500]}```" for s, msg in failures] or ["None."]
    Path(args.report).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:6]))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
